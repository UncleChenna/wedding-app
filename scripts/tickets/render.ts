import { byId, criticalPath, isClosed, isHuman, pickOrder, upcoming } from "./graph";
import { EPICS, ESTIMATE_HOURS, ESTIMATE_POINTS, MILESTONES, STATUSES } from "./model";
import type { Frontmatter, Status } from "./model";

/**
 * Renderers. BOARD.md and ROADMAP.md are generated from the committed ticket
 * files only (no dates, no ledger), so the same files always render the same.
 */

const BOARD_ORDER: Status[] = [
  "in_progress",
  "in_review",
  "blocked",
  "todo",
  "backlog",
  "done",
  "cancelled",
];
const LABEL: Record<Status, string> = {
  backlog: "Backlog",
  todo: "Todo",
  in_progress: "In progress",
  in_review: "In review",
  done: "Done",
  blocked: "Blocked",
  cancelled: "Cancelled",
};

const link = (m: Frontmatter, slugs: Map<string, string>) => `[${m.id}](${slugs.get(m.id) ?? ""})`;
const cell = (s: string) => s.replaceAll("|", "\\|");

function bar(done: number, total: number, width = 20): string {
  const filled = total ? Math.round((done / total) * width) : 0;
  return `${"█".repeat(filled)}${"░".repeat(width - filled)}`;
}

function epicProgress(metas: readonly Frontmatter[]): string[] {
  const rows = EPICS.map((epic) => {
    const all = metas.filter((m) => m.epic === epic.key && m.status !== "cancelled");
    const done = all.filter((m) => m.status === "done").length;
    const pct = all.length ? Math.round((done / all.length) * 100) : 0;
    return `${epic.title.padEnd(36)} ${bar(done, all.length)} ${String(done).padStart(3)}/${String(all.length).padEnd(3)} ${String(pct).padStart(3)}%`;
  });
  return ["```text", ...rows, "```"];
}

function pathLines(
  metas: readonly Frontmatter[],
  path: string[],
  slugs: Map<string, string>,
): string[] {
  const map = byId(metas);
  return path.map((id, i) => {
    const m = map.get(id);
    return m
      ? `${i + 1}. ${link(m, slugs)} ${cell(m.title)} · ${m.estimate} · ${m.status}`
      : `${i + 1}. ${id}`;
  });
}

const hours = (metas: readonly Frontmatter[], ids: readonly string[]) => {
  const map = byId(metas);
  return ids.reduce((sum, id) => {
    const m = map.get(id);
    return sum + (m && !isClosed(m) ? ESTIMATE_HOURS[m.estimate] : 0);
  }, 0);
};

export function renderBoard(metas: readonly Frontmatter[], paths: Map<string, string>): string {
  const slugs = new Map([...paths].map(([id, path]) => [id, path.replace(/^tickets\//, "")]));
  const out = [
    "# Ticket board",
    "",
    "<!-- Local snapshot generated by `pnpm t:render`. Regenerate to refresh. -->",
    "",
    "Live state (including claims not yet merged): `pnpm t:board`. Rules: [docs/tickets.md](../../docs/tickets.md).",
    "",
    "## Progress by epic",
    "",
    ...epicProgress(metas),
    "",
  ];
  const overall = criticalPath(metas);
  out.push(
    "## Critical path",
    "",
    `Longest remaining dependency chain: ${overall.path.length} tickets, ${overall.points} points (about ${hours(metas, overall.path)} agent-hours).`,
    "",
    ...pathLines(metas, overall.path, slugs),
    "",
    "## Next 10",
    "",
    "Agent work in `pnpm t:next` order (priority, then work unblocked, then id), assuming in-flight work and the human tasks below land in parallel.",
    "",
    "| # | Ticket | Title | Priority | Est. | Module |",
    "| - | ------ | ----- | -------- | ---- | ------ |",
    ...upcoming(metas, 10, { skip: isHuman }).map(
      (m, i) =>
        `| ${i + 1} | ${link(m, slugs)} | ${cell(m.title)} | ${m.priority} | ${m.estimate} | ${m.module} |`,
    ),
    "",
    "## Waiting on people",
    "",
    "Open tickets labelled `human` (decisions, accounts, physical tasks), in `pnpm t:next --human` order. Do these early so agents are never blocked.",
    "",
    "| # | Ticket | Title | Priority | Status | Blocked by |",
    "| - | ------ | ----- | -------- | ------ | ---------- |",
    ...metas
      .filter((m) => isHuman(m) && !isClosed(m))
      .sort(pickOrder(metas))
      .map(
        (m, i) =>
          `| ${i + 1} | ${link(m, slugs)} | ${cell(m.title)} | ${m.priority} | ${m.status} | ${m.blocked_by.filter((d) => !metas.some((x) => x.id === d && x.status === "done")).join(", ")} |`,
      ),
    "",
    "## Board",
    "",
  );
  for (const status of BOARD_ORDER) {
    const group = metas.filter((m) => m.status === status);
    out.push(`### ${LABEL[status]} (${group.length})`, "");
    if (!group.length) {
      out.push("_None._", "");
      continue;
    }
    out.push(
      "| Ticket | Title | Epic | Priority | Est. | Owner | Blocked by |",
      "| ------ | ----- | ---- | -------- | ---- | ----- | ---------- |",
    );
    for (const m of group)
      out.push(
        `| ${link(m, slugs)} | ${cell(m.title)} | ${m.epic} | ${m.priority} | ${m.estimate} | ${m.owner} | ${m.blocked_by.join(", ")} |`,
      );
    out.push("");
  }
  return out.join("\n");
}

export function renderRoadmap(metas: readonly Frontmatter[], paths: Map<string, string>): string {
  const slugs = new Map([...paths].map(([id, path]) => [id, path.replace(/^tickets\//, "")]));
  const out = [
    "# Roadmap",
    "",
    "<!-- Local snapshot generated by `pnpm t:render`. Regenerate to refresh. -->",
    "",
    "Epics in delivery order. Points: S = 1, M = 2, L = 4 (L is about half a day of agent work).",
    "",
    "| # | Epic | Goal | Tickets | Done | Open points | Human |",
    "| - | ---- | ---- | ------- | ---- | ----------- | ----- |",
  ];
  EPICS.forEach((epic, i) => {
    const all = metas.filter((m) => m.epic === epic.key && m.status !== "cancelled");
    const open = all
      .filter((m) => !isClosed(m))
      .reduce((s, m) => s + ESTIMATE_POINTS[m.estimate], 0);
    out.push(
      `| ${i + 1} | ${epic.title} | ${epic.goal} | ${all.length} | ${all.filter((m) => m.status === "done").length} | ${open} | ${all.filter((m) => m.labels.includes("human")).length} |`,
    );
  });
  const total = metas.filter((m) => m.status !== "cancelled");
  out.push(
    `| | **Total** | | **${total.length}** | **${total.filter((m) => m.status === "done").length}** | **${total.filter((m) => !isClosed(m)).reduce((s, m) => s + ESTIMATE_POINTS[m.estimate], 0)}** | **${total.filter((m) => m.labels.includes("human")).length}** |`,
    "",
  );
  for (const milestone of MILESTONES) {
    const path = criticalPath(metas, milestone.id);
    out.push(
      `## Critical path: ${milestone.name}`,
      "",
      `Target ${milestone.id}. ${path.path.length} open tickets in the longest chain, ${path.points} points (about ${hours(metas, path.path)} agent-hours of serial work; parallel work happens alongside).`,
      "",
      ...pathLines(metas, path.path, slugs),
      "",
    );
  }
  out.push("## Tickets by epic", "");
  for (const epic of EPICS) {
    const group = metas.filter((m) => m.epic === epic.key);
    out.push(
      `### ${epic.title}`,
      "",
      ...group.map(
        (m) =>
          `- ${link(m, slugs)} ${cell(m.title)} · ${m.priority} · ${m.estimate} · ${m.status}${m.labels.includes("human") ? " · human" : ""}`,
      ),
      "",
    );
  }
  return out.join("\n");
}

/** Terminal kanban: one column per active status. */
export function renderTerminalBoard(
  metas: readonly Frontmatter[],
  width = process.stdout.columns || 160,
): string {
  const columns: Status[] = ["todo", "in_progress", "in_review", "blocked", "done"];
  const colWidth = Math.max(24, Math.floor((width - (columns.length - 1) * 3) / columns.length));
  const cells = columns.map((status) => {
    const group = metas.filter((m) => m.status === status);
    const shown = status === "done" ? group.slice(-12) : group;
    const lines = shown.map((m) => {
      const who = m.owner ? ` @${m.owner}` : "";
      const text = `${m.id} ${m.title}`;
      return (
        (text.length + who.length > colWidth
          ? `${text.slice(0, colWidth - who.length - 1)}…`
          : text) + who
      );
    });
    if (status === "done" && group.length > shown.length)
      lines.unshift(`… ${group.length - shown.length} earlier`);
    return [`${LABEL[status].toUpperCase()} (${group.length})`, "─".repeat(colWidth), ...lines];
  });
  const height = Math.max(...cells.map((c) => c.length));
  const rows: string[] = [];
  for (let r = 0; r < height; r++)
    rows.push(
      cells
        .map((c) => (c[r] ?? "").padEnd(colWidth))
        .join(" │ ")
        .trimEnd(),
    );
  const counts = (["backlog", "cancelled"] as Status[]).map(
    (s) => `${LABEL[s]}: ${metas.filter((m) => m.status === s).length}`,
  );
  return `${rows.join("\n")}\n\n${counts.join(" · ")}`;
}

export function renderList(metas: readonly Frontmatter[]): string {
  const rows = metas.map((m) => [
    m.id,
    m.status,
    m.priority,
    m.estimate,
    m.epic,
    m.module,
    m.owner || "-",
    m.title,
  ]);
  const header = ["ID", "STATUS", "PRIORITY", "EST", "EPIC", "MODULE", "OWNER", "TITLE"];
  const widths = header.map((h, i) => Math.max(h.length, ...rows.map((r) => (r[i] ?? "").length)));
  const fmt = (r: string[]) =>
    r.map((c, i) => (i === r.length - 1 ? c : c.padEnd(widths[i] ?? 0))).join("  ");
  return [fmt(header), ...rows.map(fmt), "", `${rows.length} tickets`].join("\n");
}

export const statusLabel = (s: Status) => LABEL[s];
export const ALL_STATUSES = STATUSES;
