import { describe, expect, it } from "vitest";

import { normalisePhone } from "../lib/phone";

describe("normalisePhone", () => {
  it.each([
    ["07700 900123", "+447700900123"],
    ["+44 7700 900123", "+447700900123"],
    ["447700900123", "+447700900123"],
    ["0044 7700 900123", "+447700900123"],
    ["+44 (0)7700 900123", "+447700900123"],
    ["0044 (0) 7700 900123", "+447700900123"],
    ["(07700) 900-123", "+447700900123"],
    [" 07700\u00a0900.123 ", "+447700900123"],
    ["020 7946 0123", "+442079460123"],
    ["016977 1234", "+44169771234"],
    ["+234 803 123 4567", "+2348031234567"],
    ["00234 803 123 4567", "+2348031234567"],
    ["+1 (202) 555-0123", "+12025550123"],
    ["+39 06 6982 0000", "+390669820000"],
    ["+123456789012345", "+123456789012345"],
  ])("normalises %s", (input, phone) => {
    expect(normalisePhone(input)).toEqual({ ok: true, phone });
    expect(normalisePhone(phone)).toEqual({ ok: true, phone });
  });

  it.each([
    "",
    " ",
    null,
    undefined,
    7700900123,
    {},
    [],
    true,
    "not a phone",
    "07700 900123 ext 4",
    "+44 7700 900123#4",
    "+44 7700 900123;ext=4",
    "07700/900123",
    "07700\n900123",
    "++447700900123",
    "44+7700900123",
    "+0447700900123",
    "+4407700900123",
    "004407700900123",
    "+44(00)7700900123",
    "(07700 900123",
    "07700)900123(",
    "((07700))900123",
    "0770090012",
    "077009001234",
    "999",
    "00000000000",
    "7700900123",
    "2348031234567",
    "+1",
    "+123456",
    "+1234567890123456",
    "+",
    "00",
    "０７７００９００１２３",
    "0".repeat(300),
  ])("returns a typed error for invalid input %j", (input) => {
    const result = normalisePhone(input);
    expect(result.ok).toBe(false);
    if (!result.ok) {
      expect(result.error.code).toBe("INVALID_PHONE");
      expect(result.error.message).toBeTruthy();
    }
  });
});
